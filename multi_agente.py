            for no, dados in evento.items():
                for msg in dados.get("messages", []):
                    if hasattr(msg, "tool_calls") and msg.tool_calls:
                        for tc in msg.tool_calls:
                            args = ", ".join(f'{k}="{v}"' for k, v in tc["args"].items())
