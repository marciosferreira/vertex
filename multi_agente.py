"""Definimos `send_email` com um parâmetro `sender` adicional. Alertas são enviados de `nao_responda@curso.ia` — assim o remetente fica claro para os destinatários."""

from langchain_core.tools import tool
from typing import Optional
from concurrent.futures import ThreadPoolExecutor, as_completed

@tool
def send_email(
    to: list[str],
    subject: str,
    body: str,
    cc: Optional[str] = None,
    sender: str = "nao_responda@curso.ia",
) -> str:
    """Envia um e-mail para um ou mais destinatários em paralelo.

    Args:
        to: Lista de e-mails dos destinatários (ex: ["aluno01@curso.ia", "aluno02@curso.ia"])
        subject: Assunto do e-mail
        body: Corpo completo do e-mail
        cc: E-mails em cópia, separados por vírgula (opcional)
        sender: Remetente do e-mail (padrão: nao_responda@curso.ia)
    """
    def _send_one(email):
        payload = {"to": email, "subject": subject, "body": body, "sender": sender}
        if cc:
            payload["cc"] = cc
        r = requests.post(f"{EMAIL_URL}/emails/send", headers=_headers, json=payload)
        ok = r.status_code in (200, 201)
        return email, ok

    results = []
    with ThreadPoolExecutor() as executor:
        futures = {executor.submit(_send_one, e): e for e in to}
        for f in as_completed(futures):
            email, ok = f.result()
            results.append(f"{'✓' if ok else '✗'} {email}")

    total = len(results)
    ok_count = sum(1 for r in results if r.startswith("✓"))
    summary = "\n".join(results)
    return f"{ok_count}/{total} e-mails enviados com sucesso:\n{summary}"

